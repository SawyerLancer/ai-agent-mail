"""Недоверенный текст в промпте: нейтрализация наших тегов данных.

Письмо, история, указания и черновик попадают в промпт внутри тегов вида
<письмо>…</письмо>. Если в самом тексте встретится «</письмо>», он закроет
блок, и дальнейший текст модель прочтёт как наш, а не как данные. Поэтому
любые похожие на наши теги — открывающие и закрывающие, в любом месте строки,
в любом регистре, с пробелами внутри — превращаем в безобидные ‹…›.

Одна функция для всех мест, где недоверенный текст попадает в промпт.
"""
from __future__ import annotations

import re

# Все теги данных, которые мы используем в промптах (app/llm.py, thread_context.py).
DATA_TAGS = (
    "письмо",
    "письмо_истории",
    "история_переписки",
    "указание_пользователя",
    "стиль_пользователя",
    "черновик",
    "контекст",
    "текст_пользователя",
    "тексты_пользователя",
    "правки_черновика",
    "текущие_правила",
)

_TAG = re.compile(
    r"<\s*/?\s*(?:" + "|".join(sorted(DATA_TAGS, key=len, reverse=True)) + r")\b[^<>]*>?",
    re.IGNORECASE,
)


# Символы, которые модель может прочитать как угловые скобки. Замена 1:1 по
# символу — позиции в тексте не сдвигаются, поэтому ищем по нормализованной
# копии, а меняем в исходной. Гомоглифы в имени тега (латинская «c» в «письмо»)
# не ловим — ограничение, см. skill email-actions-safety.
_BRACKETS = str.maketrans({
    # «» — обычные кавычки в русском тексте, ‹› — наша безопасная форма: не трогаем
    "＜": "<", "﹤": "<", "〈": "<", "⟨": "<", "〈": "<",
    "＞": ">", "﹥": ">", "〉": ">", "⟩": ">", "〉": ">",
    "／": "/", "∕": "/", "⁄": "/",
})


def escape(text: str | None) -> str:
    """«<письмо>», «</ ПИСЬМО >», «＜/письмо＞», «< /письмо_истории x=1>» → «‹…›»."""
    if not text:
        return ""
    probe = text.translate(_BRACKETS)
    out, last = [], 0
    for m in _TAG.finditer(probe):
        inner = probe[m.start() : m.end()].strip("<>").strip()
        out.append(text[last : m.start()])
        out.append("‹" + inner + "›")
        last = m.end()
    out.append(text[last:])
    return "".join(out)


def restore_user_tags(original: str, processed: str) -> str:
    """Вернуть в результат модели теги, которые были в тексте пользователя.

    escape превращает «<письмо>» в «‹письмо›» перед отправкой модели; модель
    возвращает текст с «‹письмо›». Для «Своего текста» это порча — меняем
    обратно, но только формы, которые escape сделал из оригинала.
    """
    probe = (original or "").translate(_BRACKETS)
    for m in _TAG.finditer(probe):
        raw = original[m.start() : m.end()]
        escaped = "‹" + m.group(0).strip("<>").strip() + "›"
        if raw != escaped:
            processed = processed.replace(escaped, raw)
    return processed


def attr(value: str | None) -> str:
    """Значение атрибута тега: без кавычек и угловых скобок, в одну строку."""
    return " ".join(re.sub(r"[\"<>\r\n]+", " ", value or "").split())
